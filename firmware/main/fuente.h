// Las mayúsculas ocupan las 7 filas: no cabe el acento, se dibujan sin él.
static uint32_t fuente_sin_acento(uint32_t cp) {
    switch (cp) {
        case 0xC1: return 'A'; case 0xC9: return 'E'; case 0xCD: return 'I';
        case 0xD3: return 'O'; case 0xDA: case 0xDC: return 'U'; case 0xD1: return 0xF1; // Ñ → ñ
        default: return cp;
    }
}

static const uint8_t *fuente_glifo(uint32_t cp) {
    cp = fuente_sin_acento(cp);
    if (cp >= 0x20 && cp <= 0x7E) return FUENTE_ASCII[cp - 0x20];
    for (unsigned i = 0; i < sizeof FUENTE_EXTRA / sizeof FUENTE_EXTRA[0]; i++)
        if (FUENTE_EXTRA[i].cp == cp) return FUENTE_EXTRA[i].g;
    return FUENTE_ASCII['?' - 0x20];
}
